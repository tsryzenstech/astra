"""Generates sysboard/qml/EmojiData.qml from Unicode's emoji-test.txt.

The repertoire matches the bundled Noto Color Emoji font (Unicode 16):
    curl -O https://unicode.org/Public/emoji/16.0/emoji-test.txt
    python3 tools/emoji/make_emoji.py emoji-test.txt

Every fully-qualified emoji is listed once, in Unicode order, by group.
Skin tone variants are not listed: they hang off their base emoji (hold
an emoji on the keyboard to pick one).
"""
import json
import os
import re
import sys

GROUPS = [  # Unicode group -> (id, symbol icon on the keyboard)
    ("Smileys & Emotion", "smileys", "\U0001F600"),
    ("People & Body", "people", "\U0001F44B"),
    ("Animals & Nature", "nature", "\U0001F43B"),
    ("Food & Drink", "food", "\U0001F354"),
    ("Travel & Places", "travel", "\U0001F697"),
    ("Activities", "activities", "\u26BD"),
    ("Objects", "objects", "\U0001F4A1"),
    ("Symbols", "symbols", "\u2764\uFE0F"),
    ("Flags", "flags", "\U0001F3F3\uFE0F"),
]
TONES = {"\U0001F3FB", "\U0001F3FC", "\U0001F3FD", "\U0001F3FE", "\U0001F3FF"}


def main(path, out):
    groups = {g[0]: [] for g in GROUPS}
    names = {}
    tones = {}
    group = None
    line_re = re.compile(r"^([0-9A-F ]+);\s*fully-qualified\s*#\s*\S+\s+E[\d.]+\s+(.*)$")
    for line in open(path, encoding="utf-8"):
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        m = line_re.match(line.strip())
        if not m or group not in groups:
            continue
        chars = "".join(chr(int(c, 16)) for c in m.group(1).split())
        if any(t in chars for t in TONES):
            base = "".join(c for c in chars if c not in TONES)
            # Multi-person sequences with two tones are left out: one tone
            # per emoji keeps the picker simple, like on most phones.
            if sum(c in TONES for c in chars) == 1:
                tones.setdefault(base, []).append(chars)
            continue
        groups[group].append(chars)
        names[chars] = m.group(2)
    data = {
        "groups": [{"id": gid, "icon": icon, "emoji": groups[name]} for name, gid, icon in GROUPS],
        "tones": {b: t for b, t in tones.items() if b in names and len(t) == 5},
        "names": names,
    }
    count = sum(len(g["emoji"]) for g in data["groups"])
    with open(out, "w", encoding="utf-8") as f:
        f.write("// SPDX-License-Identifier: Apache-2.0\n")
        f.write("// Generated by tools/emoji/make_emoji.py from Unicode emoji-test.txt (16.0). Do not edit.\n")
        f.write("pragma Singleton\nimport QtQml\n\nQtObject {\n")
        f.write("    // [{ id, icon, emoji: [..] }] in keyboard order\n")
        f.write("    readonly property var groups: " + json.dumps(data["groups"], ensure_ascii=False) + "\n")
        f.write("    // base emoji -> its five skin tone variants\n")
        f.write("    readonly property var tones: " + json.dumps(data["tones"], ensure_ascii=False) + "\n")
        f.write("    // emoji -> English CLDR name (search)\n")
        f.write("    readonly property var names: " + json.dumps(data["names"], ensure_ascii=False) + "\n")
        f.write("}\n")
    print(f"{count} emoji, {len(data['tones'])} with skin tones -> {out}")


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    main(sys.argv[1], os.path.join(root, "sysboard", "qml", "EmojiData.qml"))
